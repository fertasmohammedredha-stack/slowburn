// Generates src/styles/tokens.css from replica/design/tokens*.json (the source of truth).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const light = JSON.parse(readFileSync(join(root, 'replica/design/tokens.json'), 'utf8'));
const dark = JSON.parse(readFileSync(join(root, 'replica/design/tokens.dark.json'), 'utf8'));

const colorVars = (c) => Object.entries(c).map(([k, v]) => `  --${k}: ${v};`).join('\n');
const typeVars = Object.entries(light.type)
  .map(([k, t]) => `  --fs-${k}: ${t.size / 16}rem;\n  --lh-${k}: ${t.line / t.size};\n  --fw-${k}: ${t.weight};`)
  .join('\n');
const spaceVars = light.space.map((v, i) => `  --space-${i}: ${v / 16}rem;`).join('\n');
const radiusVars = Object.entries(light.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n');
const motionVars = Object.entries(light.motion).map(([k, v]) => `  --motion-${k}: ${v};`).join('\n');

const css = `/* GENERATED by scripts/gen-tokens.mjs from replica/design/tokens*.json. Do not edit by hand. */
@layer reset, base, components, pages;

:root {
  --font-display: ${light.font.display};
  --font-sans: ${light.font.sans};
  --font-mono: ${light.font.mono};
${typeVars}
${spaceVars}
${radiusVars}
${motionVars}
}

:root,
[data-theme="light"] {
  color-scheme: light;
${colorVars(light.color)}
  --shadow-card: ${light.shadow.card};
  --shadow-pop: ${light.shadow.pop};
  --grain-opacity: 0.07;
}

[data-theme="dark"] {
  color-scheme: dark;
${colorVars(dark.color)}
  --shadow-card: ${dark.shadow.card};
  --shadow-pop: ${dark.shadow.pop};
  --grain-opacity: 0.09;
}

/* The accent follows the current phase of the timer. */
:root,
[data-mode="focus"] { --accent: var(--accent-focus); }
[data-mode="short"] { --accent: var(--accent-short); }
[data-mode="long"] { --accent: var(--accent-long); }
`;
writeFileSync(join(root, 'src/styles/tokens.css'), css);
console.log('wrote src/styles/tokens.css');
